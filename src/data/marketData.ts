function generateCandles(basePrice: number, volatility: number, count = 30): { time: string; open: number; high: number; low: number; close: number; volume: number }[] {
  const candles = [];
  let current = basePrice * 0.95;
  const now = new Date();
  
  for (let i = count; i >= 0; i--) {
    const d = new Date(now.getTime() - i * 3600 * 1000 * 4);
    const timeStr = d.toLocaleDateString('en-US', { month: 'short', day: 'numeric', hour: '2-digit', minute: '2-digit' });
    
    const change = (Math.random() - 0.48) * volatility * current;
    const open = current;
    const close = Math.max(open + change, 0.001);
    const high = Math.max(open, close) + Math.random() * volatility * 0.6 * current;
    const low = Math.max(Math.min(open, close) - Math.random() * volatility * 0.6 * current, 0.0001);
    const volume = Math.floor(basePrice * (5000 + Math.random() * 25000));
    
    candles.push({
      time: timeStr,
      open: Number(open.toFixed(2)),
      high: Number(high.toFixed(2)),
      low: Number(low.toFixed(2)),
      close: Number(close.toFixed(2)),
      volume,
    });
    
    current = close;
  }
  return candles;
}

